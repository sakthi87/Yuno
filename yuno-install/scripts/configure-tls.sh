#!/usr/bin/env bash
set -euo pipefail

: "${YUNO_PUBLIC_HOST:?}"
: "${YUNO_INSTALL_ROOT:?}"
: "${YUNO_API_PORT:?}"

TLS_DIR="${YUNO_INSTALL_ROOT}/tls"
mkdir -p "$TLS_DIR"

if [[ ! -f "$TLS_DIR/server.crt" || ! -f "$TLS_DIR/server.key" ]]; then
  echo "Generating self-signed TLS certificate for ${YUNO_PUBLIC_HOST}..."
  openssl req -x509 -nodes -days 825 -newkey rsa:2048 \
    -keyout "$TLS_DIR/server.key" \
    -out "$TLS_DIR/server.crt" \
    -subj "/CN=${YUNO_PUBLIC_HOST}/O=Yugabyte Platform/C=US"
  chmod 600 "$TLS_DIR/server.key"
  chmod 644 "$TLS_DIR/server.crt"
fi

NGINX_CONF="/etc/nginx/conf.d/yuno-platform.conf"
sudo tee "$NGINX_CONF" > /dev/null <<EOF
# Yugabyte Platform — TLS termination (generated by yuno-install)
upstream yuno_api {
  server 127.0.0.1:${YUNO_API_PORT};
}

server {
  listen 443 ssl;
  server_name ${YUNO_PUBLIC_HOST};

  ssl_certificate     ${TLS_DIR}/server.crt;
  ssl_certificate_key ${TLS_DIR}/server.key;
  ssl_protocols       TLSv1.2 TLSv1.3;

  location / {
    proxy_pass http://yuno_api;
    proxy_http_version 1.1;
    proxy_set_header Host \$host;
    proxy_set_header X-Real-IP \$remote_addr;
    proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto https;
  }
}

server {
  listen 80;
  server_name ${YUNO_PUBLIC_HOST};
  return 301 https://\$host\$request_uri;
}
EOF

if command -v nginx >/dev/null 2>&1; then
  sudo nginx -t
  sudo systemctl enable nginx
  sudo systemctl restart nginx
  echo "TLS configured via nginx on https://${YUNO_PUBLIC_HOST}/"
else
  echo "nginx not installed — TLS cert generated at ${TLS_DIR}; install nginx from offline bundle"
fi
