#!/usr/bin/env bash

prompt_install_inputs() {
  echo
  echo "=== Yugabyte Platform Production Install ==="

  if [[ "${OFFLINE_INSTALL:-false}" == "true" ]]; then
    echo "Mode: OFFLINE (air-gapped bundle)"
  else
    read -r -p "Offline/air-gapped install? [y/N]: " OFFLINE_ANS
    if [[ "${OFFLINE_ANS:-N}" =~ ^[Yy] ]]; then
      export OFFLINE_INSTALL=true
    fi
  fi

  read -r -p "Company name [Yugabyte Platform]: " YUNO_COMPANY_NAME
  YUNO_COMPANY_NAME="${YUNO_COMPANY_NAME:-Yugabyte Platform}"

  read -r -p "Install root [/opt/yuno]: " YUNO_INSTALL_ROOT
  YUNO_INSTALL_ROOT="${YUNO_INSTALL_ROOT:-/opt/yuno}"

  read -r -p "API port (internal) [8080]: " YUNO_API_PORT
  YUNO_API_PORT="${YUNO_API_PORT:-8080}"

  read -r -p "Public hostname [localhost]: " YUNO_PUBLIC_HOST
  YUNO_PUBLIC_HOST="${YUNO_PUBLIC_HOST:-localhost}"

  read -r -p "Enable TLS via nginx? [Y/n]: " ENABLE_TLS
  ENABLE_TLS="${ENABLE_TLS:-Y}"
  TLS_PORT=443

  read -r -p "PostgreSQL host [127.0.0.1]: " PGHOST
  PGHOST="${PGHOST:-127.0.0.1}"

  read -r -p "PostgreSQL port [5432]: " PGPORT
  PGPORT="${PGPORT:-5432}"

  read -r -p "Database name [yuno_platform]: " PGDATABASE
  PGDATABASE="${PGDATABASE:-yuno_platform}"

  read -r -p "Database user [yuno]: " PGUSER
  PGUSER="${PGUSER:-yuno}"

  while [[ -z "${PGPASSWORD:-}" ]]; do
    read -r -s -p "Database password for ${PGUSER}: " PGPASSWORD
    echo
  done

  if [[ "$OFFLINE_INSTALL" == "true" ]]; then
    INSTALL_LOCAL_PG=Y
    log_install "INFO" "Offline mode: PostgreSQL packages must be in bundle/packages/"
  else
    read -r -p "Install local PostgreSQL if missing? [Y/n]: " INSTALL_LOCAL_PG
    INSTALL_LOCAL_PG="${INSTALL_LOCAL_PG:-Y}"
  fi

  read -r -p "Enable demo seed data (lab only)? [y/N]: " AUTO_SEED_INPUT
  AUTO_SEED_INPUT="${AUTO_SEED_INPUT:-N}"
  if [[ "$AUTO_SEED_INPUT" =~ ^[Yy] ]]; then
    AUTO_SEED=true
  else
    AUTO_SEED=false
  fi

  export YUNO_COMPANY_NAME YUNO_INSTALL_ROOT YUNO_API_PORT YUNO_PUBLIC_HOST
  export PGHOST PGPORT PGDATABASE PGUSER PGPASSWORD INSTALL_LOCAL_PG AUTO_SEED ENABLE_TLS TLS_PORT

  log_success "0" "Collected install inputs for company: $YUNO_COMPANY_NAME"
}

write_runtime_config() {
  local config_dir="${CONFIG_DIR:-/etc/yuno}"
  local config_file="${config_dir}/yuno.env"
  local secrets_file="${config_dir}/secrets.env"
  local database_url="postgresql://${PGUSER}:${PGPASSWORD}@${PGHOST}:${PGPORT}/${PGDATABASE}"

  generate_api_tokens

  mkdir -p "$config_dir" 2>/dev/null || sudo mkdir -p "$config_dir"

  cat > "${secrets_file}.tmp" <<EOF
# Yugabyte Platform secrets — chmod 600
AGENT_API_TOKEN=${AGENT_API_TOKEN}
ADMIN_API_TOKEN=${ADMIN_API_TOKEN}
PGPASSWORD=${PGPASSWORD}
EOF

  cat > "${config_file}.tmp" <<EOF
# Generated by yuno-install on $(date -u +%Y-%m-%dT%H:%M:%SZ)
YUNO_COMPANY_NAME=${YUNO_COMPANY_NAME}
YUNO_CONFIG_PATH=${config_file}
YUNO_INSTALL_ROOT=${YUNO_INSTALL_ROOT}
HOST=127.0.0.1
PORT=${YUNO_API_PORT}
COLLECTOR_URL=https://${YUNO_PUBLIC_HOST}/api/v1/ingest
DB_DRIVER=postgres
DATABASE_URL=${database_url}
AUTO_SEED=${AUTO_SEED}
STATIC_DIR=${YUNO_INSTALL_ROOT}/ui
OFFLINE_INSTALL=${OFFLINE_INSTALL:-false}
TLS_ENABLED=$([[ "${ENABLE_TLS:-N}" =~ ^[Yy] ]] && echo true || echo false)
TLS_CERT_PATH=${YUNO_INSTALL_ROOT}/tls/server.crt
TLS_KEY_PATH=${YUNO_INSTALL_ROOT}/tls/server.key

# Include secrets — loaded separately by Node (do not commit)
# AGENT_API_TOKEN and ADMIN_API_TOKEN live in ${config_dir}/secrets.env
EOF

  if [[ -w "$config_dir" ]]; then
    mv "${secrets_file}.tmp" "$secrets_file"
    mv "${config_file}.tmp" "$config_file"
    chmod 600 "$secrets_file"
    chmod 640 "$config_file"
  else
    sudo mv "${secrets_file}.tmp" "$secrets_file"
    sudo mv "${config_file}.tmp" "$config_file"
    sudo chmod 600 "$secrets_file"
    sudo chmod 640 "$config_file"
  fi

  export YUNO_CONFIG_PATH="$config_file"
  export DATABASE_URL="$database_url"
  export STATIC_DIR="${YUNO_INSTALL_ROOT}/ui"
  export PORT="$YUNO_API_PORT"
  export AGENT_API_TOKEN ADMIN_API_TOKEN

  secure_config_permissions
  log_success "2" "Wrote config to $config_file and secrets to $secrets_file"
}
